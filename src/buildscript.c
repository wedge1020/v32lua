#include "v32lua.h"
#include "buildscript.h"

#ifndef _WIN32
#include <sys/stat.h>
#endif

// ----------------------------------------------------------------------------
// Make.sh / Make.bat
//
// The scripts repeat the steps the Vircon32 DevTools need, in the form the
// ecosystem's own projects use (see the tools' sample Make.sh / Make.bat):
// compile (v32lua, which also writes the XML), convert the textures and
// sounds the --# hints name, assemble, pack. When v32opt is installed, the
// optimized build (v32opt, assemble, pack of the Opt XML) follows; without
// it that path is skipped. The scripts check for v32lua first.
//
// All paths in a script are relative to the script's own folder (it changes
// into it first), so it works from anywhere.
// ----------------------------------------------------------------------------

#define GENERATED_MARK  "Generated by v32lua"

typedef struct
{
    char *src;              // file to convert / copy, relative to the script folder
    char *dest;             // where the XML expects it, likewise
    int   convert;          // 1: run png2vircon / wav2vircon on src; 0: copy src to dest
    int   is_texture;
} Asset;

typedef struct
{
    char          *name;            // output base name ("game")
    char          *input;           // source file
    char          *asm_file, *asm_opt;
    char          *vbin,     *vbin_opt;
    char          *xml,      *xml_opt;
    char          *rom,      *rom_opt;      // bin/game.v32, bin/gameOpt.v32
    char         **dirs;                    // folders to create
    int            ndirs;
    Asset         *assets;
    int            nassets;
    const BuildOpt *opts;
    int            nopts;
    char          *script_dir;              // absolute
    int            debug_map;
} Plan;

// ---- small helpers ---------------------------------------------------------

static char *dup_or_die (const char *s)
{
    char *r = strdup (s);
    if (r == NULL) { fprintf (stderr, "Compiler Error: out of memory\n"); exit (2); }
    return r;
}

static char *join_path (const char *dir, const char *name)
{
    if (strcmp (dir, ".") == 0 || dir[0] == '\0') return dup_or_die (name);

    char *r = malloc (strlen (dir) + strlen (name) + 2);
    if (r == NULL) { fprintf (stderr, "Compiler Error: out of memory\n"); exit (2); }
    sprintf (r, "%s/%s", dir, name);
    return r;
}

static int file_exists (const char *path)
{
    FILE *f = fopen (path, "rb");
    if (f == NULL) return 0;
    fclose (f);
    return 1;
}

// Where the file a hint names lives, as a path usable from here: the way it
// is written if that exists (hints are read from the current directory, as
// pico8_assets.c does), else next to the source file. Neither found: the XML's
// own point of reference -- the source file's folder with
// --xml-preserve-paths, the current directory otherwise.
static char *resolve_asset (const char *hint, const char *src_dir, int preserve_paths)
{
    if (file_exists (hint)) return dup_or_die (hint);

    char *beside = join_path (src_dir, hint);
    if (file_exists (beside) || preserve_paths) return beside;
    free (beside);
    return dup_or_die (hint);
}

static const char *extension_of (const char *path)
{
    const char *dot = strrchr (path, '.');
    const char *sep = path_basename (path);
    return (dot != NULL && dot >= sep) ? dot : "";
}

// Relative to the script folder, '/' separated. Caller frees.
static char *rel (const Plan *plan, const char *path)
{
    return path_relative_to (plan->script_dir, path);
}

// ---- quoting ---------------------------------------------------------------

// A rotating set of buffers, so several words can be used in one printf.
static const char *word (int bat, const char *s)
{
    static char *ring[16];
    static int   next;
    int          safe   = 1;
    size_t       n      = strlen (s);
    char        *out;

    next = (next + 1) % 16;
    free (ring[next]);
    ring[next] = out = malloc (n * 4 + 4);
    if (out == NULL) { fprintf (stderr, "Compiler Error: out of memory\n"); exit (2); }

    for (const char *c = s; *c; c++)
    {
        if (!(isalnum ((unsigned char) *c) || strchr ("_./+-:@,=", *c))) safe = 0;
    }
    if (n == 0) safe = 0;

    char *w = out;
    if (bat)
    {
        // Windows: backslashes, "double quotes" around anything unusual, and a doubled %.
        if (!safe) *w++ = '"';
        for (const char *c = s; *c; c++)
        {
            if (*c == '/') *w++ = '\\';
            else if (*c == '%') { *w++ = '%'; *w++ = '%'; }
            else *w++ = *c;
        }
        if (!safe) *w++ = '"';
    }
    else
    {
        // POSIX shell: 'single quotes', with ' written as '\''.
        if (!safe) *w++ = '\'';
        for (const char *c = s; *c; c++)
        {
            if (!safe && *c == '\'') { memcpy (w, "'\\''", 4); w += 4; }
            else *w++ = *c;
        }
        if (!safe) *w++ = '\'';
    }
    *w = '\0';
    return out;
}

// printf into the script; a Windows batch file gets CR LF line ends.
static void put (FILE *f, int bat, const char *fmt, ...)
{
    char    small[1024];
    char   *buf = small;
    va_list ap, ap2;

    va_start (ap, fmt);
    va_copy (ap2, ap);
    int need = vsnprintf (small, sizeof (small), fmt, ap);
    va_end (ap);
    if (need >= (int) sizeof (small))
    {
        buf = malloc ((size_t) need + 1);
        if (buf == NULL) { fprintf (stderr, "Compiler Error: out of memory\n"); exit (2); }
        vsnprintf (buf, (size_t) need + 1, fmt, ap2);
    }
    va_end (ap2);

    for (const char *c = buf; *c; c++)
    {
        if (*c == '\n' && bat) fputc ('\r', f);
        fputc (*c, f);
    }
    if (buf != small) free (buf);
}

// ---- the plan --------------------------------------------------------------

static void add_dir (Plan *plan, const char *dir)
{
    if (strcmp (dir, ".") == 0 || dir[0] == '\0') return;
    for (int i = 0; i < plan->ndirs; i++)
    {
        if (strcmp (plan->dirs[i], dir) == 0) return;
    }
    plan->dirs = realloc (plan->dirs, sizeof (char *) * (size_t) (plan->ndirs + 1));
    if (plan->dirs == NULL) { fprintf (stderr, "Compiler Error: out of memory\n"); exit (2); }
    plan->dirs[plan->ndirs++] = dup_or_die (dir);
}

static void add_dir_of (Plan *plan, const char *file)
{
    char *d = path_dirname (file);
    add_dir (plan, d);
    free (d);
}

// One entry per --#texture / --#sound the compiler did not generate itself.
static void plan_assets (Plan *plan, CARTresource *head, int is_texture, const char *xml_dir,
                         const char *src_dir, int preserve_paths)
{
    int count = 0;

    for (CARTresource *r = head; r != NULL; r = r->next) count++;
    if (count == 0) return;

    const char *tag     = is_texture ? "texture" : "sound";
    const char *out_ext = is_texture ? ".vtex"   : ".vsnd";
    const char *raw_ext = is_texture ? ".png"    : ".wav";

    cart_xml_set_quiet (1);
    char **names = cart_xml_resolve_names (head, count, tag, out_ext, preserve_paths, xml_dir);
    cart_xml_set_quiet (0);

    int i = 0;
    for (CARTresource *r = head; r != NULL; r = r->next, i++)
    {
        if (!r->generated)
        {
            char *dest_path = join_path (xml_dir, names[i]);
            char *dest      = rel (plan, dest_path);
            int   dup       = 0;

            for (int k = 0; k < plan->nassets; k++)
            {
                if (strcmp (plan->assets[k].dest, dest) == 0) dup = 1;
            }
            if (!dup)
            {
                // The hint names the raw file (image.png / sound.wav); one that
                // already names the converted file may have the raw one beside it.
                char  *src_hint = dup_or_die (r->filename);
                int    convert  = 0;

                if (strcasecmp (extension_of (src_hint), raw_ext) == 0)
                {
                    convert = 1;
                }
                else
                {
                    char *stem_raw = replace_extension (src_hint, raw_ext);
                    char *probe    = resolve_asset (stem_raw, src_dir, 0);
                    if (file_exists (probe))
                    {
                        free (src_hint);
                        src_hint = stem_raw;
                        convert  = 1;
                    }
                    else
                    {
                        free (stem_raw);
                        free (src_hint);
                        src_hint = replace_extension (r->filename, out_ext);
                    }
                    free (probe);
                }

                char *src_path = resolve_asset (src_hint, src_dir, preserve_paths);
                char *src      = rel (plan, src_path);

                plan->assets = realloc (plan->assets, sizeof (Asset) * (size_t) (plan->nassets + 1));
                if (plan->assets == NULL) { fprintf (stderr, "Compiler Error: out of memory\n"); exit (2); }
                plan->assets[plan->nassets].src        = src;
                plan->assets[plan->nassets].dest       = dup_or_die (dest);
                plan->assets[plan->nassets].convert    = convert;
                plan->assets[plan->nassets].is_texture = is_texture;
                plan->nassets++;
                add_dir_of (plan, dest);
                free (src_path);
                free (src_hint);
            }
            free (dest);
            free (dest_path);
        }
        free (names[i]);
    }
    free (names);
}

// ---- the scripts -----------------------------------------------------------

static void write_command (FILE *f, int bat, const char *line)
{
    // sh:  <command> || abort_build        bat:  <command> || goto :failed
    put (f, bat, "%s || %s\n", line, bat ? "goto :failed" : "abort_build");
}

static void write_script (FILE *f, int bat, const Plan *plan)
{
    char     line[4096];
    int      have_tex = 0, have_snd = 0;
    const char *dbg   = plan->debug_map ? " -g program" : "";

    for (int i = 0; i < plan->nassets; i++)
    {
        if (plan->assets[i].is_texture) have_tex = 1; else have_snd = 1;
    }

    if (bat)
    {
        put (f, bat, "@echo off\n");
        put (f, bat, "REM " GENERATED_MARK " " VERSION " for %s.\n", plan->input);
        put (f, bat, "REM Edit freely: v32lua leaves a Make.bat it did not write alone, and\n");
        put (f, bat, "REM --no-build-scripts stops it writing these.\n");
        put (f, bat, "cd /d \"%%~dp0\"\n");
        put (f, bat, "\n");
        put (f, bat, "REM v32lua is needed to build this project\n");
        put (f, bat, "where v32lua >nul 2>nul\n");
        put (f, bat, "if errorlevel 1 (\n");
        put (f, bat, "    echo.\n");
        put (f, bat, "    echo ERROR: v32lua is needed to build this project, but it was not found in your PATH\n");
        put (f, bat, "    goto :failed\n");
        put (f, bat, ")\n");
        put (f, bat, "\n");
        put (f, bat, "REM create the output folders if non existing, since\n");
        put (f, bat, "REM the development tools will not create them themselves\n");
        for (int i = 0; i < plan->ndirs; i++)
        {
            put (f, bat, "if not exist %s mkdir %s\n", word (1, plan->dirs[i]), word (1, plan->dirs[i]));
        }
    }
    else
    {
        put (f, bat, "#!/bin/bash\n");
        put (f, bat, "# " GENERATED_MARK " " VERSION " for %s.\n", plan->input);
        put (f, bat, "# Edit freely: v32lua leaves a Make.sh it did not write alone, and\n");
        put (f, bat, "# --no-build-scripts stops it writing these.\n");
        put (f, bat, "\n");
        put (f, bat, "# define an abort function to call on error\n");
        put (f, bat, "abort_build()\n{\n    echo\n    echo BUILD FAILED\n    exit 1\n}\n");
        put (f, bat, "\n");
        put (f, bat, "# work from the folder this script is in\n");
        put (f, bat, "cd \"$(dirname \"$0\")\" || abort_build\n");
        put (f, bat, "\n");
        put (f, bat, "# v32lua is needed to build this project\n");
        put (f, bat, "if ! command -v v32lua >/dev/null 2>&1; then\n");
        put (f, bat, "    echo\n");
        put (f, bat, "    echo \"ERROR: v32lua is needed to build this project, but it was not found in your PATH\"\n");
        put (f, bat, "    abort_build\n");
        put (f, bat, "fi\n");
        put (f, bat, "\n");
        put (f, bat, "# create the output folders if non existing, since\n");
        put (f, bat, "# the development tools will not create them themselves\n");
        for (int i = 0; i < plan->ndirs; i++)
        {
            put (f, bat, "mkdir -p %s\n", word (0, plan->dirs[i]));
        }
    }

    // ---- compile
    put (f, bat, "\n%s\n", bat ? "echo." : "echo");
    put (f, bat, "echo Compile the Lua code\n");
    put (f, bat, "echo --------------------------\n");
    {
        // --no-build-scripts: building must not rewrite (and so undo edits to) this script
        int n = snprintf (line, sizeof (line), "v32lua --no-build-scripts%s", plan->debug_map ? " -g" : "");
        for (int i = 0; i < plan->nopts && n < (int) sizeof (line) - 1; i++)
        {
            const BuildOpt *o = &plan->opts[i];
            n += snprintf (line + n, sizeof (line) - (size_t) n, " %s", o->flag);
            if (o->value != NULL)
            {
                char *v = o->is_path ? rel (plan, o->value) : dup_or_die (o->value);
                n += snprintf (line + n, sizeof (line) - (size_t) n, " %s", word (bat, v));
                free (v);
            }
        }
        snprintf (line + n, sizeof (line) - (size_t) n, " -o %s %s", word (bat, plan->asm_file), word (bat, plan->input));
        write_command (f, bat, line);
    }

    // ---- assets
    for (int pass = 1; pass >= 0; pass--)      // textures, then sounds
    {
        if (!(pass ? have_tex : have_snd)) continue;
        put (f, bat, "\n%s\n", bat ? "echo." : "echo");
        put (f, bat, pass ? "echo Convert the PNG textures\n" : "echo Convert the WAV sounds\n");
        put (f, bat, "echo --------------------------\n");
        for (int i = 0; i < plan->nassets; i++)
        {
            const Asset *a = &plan->assets[i];
            if (a->is_texture != pass) continue;
            if (a->convert)
            {
                snprintf (line, sizeof (line), "%s %s -o %s", pass ? "png2vircon" : "wav2vircon",
                          word (bat, a->src), word (bat, a->dest));
            }
            else if (strcmp (a->src, a->dest) == 0)
            {
                continue;       // already where the XML expects it
            }
            else
            {
                snprintf (line, sizeof (line), "%s %s %s", bat ? "copy /y" : "cp",
                          word (bat, a->src), word (bat, a->dest));
                if (bat) strcat (line, " >nul");
            }
            write_command (f, bat, line);
        }
    }

    // ---- assemble and pack
    put (f, bat, "\n%s\n", bat ? "echo." : "echo");
    put (f, bat, "echo Assemble the ASM code\n");
    put (f, bat, "echo --------------------------\n");
    snprintf (line, sizeof (line), "assemble%s %s -o %s", dbg, word (bat, plan->asm_file), word (bat, plan->vbin));
    write_command (f, bat, line);

    put (f, bat, "\n%s\n", bat ? "echo." : "echo");
    put (f, bat, "echo Pack the ROM\n");
    put (f, bat, "echo --------------------------\n");
    snprintf (line, sizeof (line), "packrom %s -o %s", word (bat, plan->xml), word (bat, plan->rom));
    write_command (f, bat, line);

    // ---- the optimized build, only when v32opt is installed
    if (bat)
    {
        put (f, bat, "\nwhere v32opt >nul 2>nul\n");
        put (f, bat, "if errorlevel 1 goto :noopt\n");
        put (f, bat, "\necho.\n");
        put (f, bat, "echo Build the optimized cart (v32opt)\n");
        put (f, bat, "echo --------------------------\n");
        put (f, bat, "v32opt -O3 -o %s %s || goto :optfailed\n", word (1, plan->asm_opt), word (1, plan->asm_file));
        put (f, bat, "assemble%s %s -o %s || goto :optfailed\n", dbg, word (1, plan->asm_opt), word (1, plan->vbin_opt));
        put (f, bat, "packrom %s -o %s || goto :optfailed\n", word (1, plan->xml_opt), word (1, plan->rom_opt));
        put (f, bat, "goto :succeeded\n");
        put (f, bat, "\n:optfailed\n");
        put (f, bat, "echo.\n");
        put (f, bat, "echo WARNING: the optimized build failed; the regular cart was still built\n");
        put (f, bat, "goto :succeeded\n");
        put (f, bat, "\n:noopt\n");
        put (f, bat, "echo.\n");
        put (f, bat, "echo v32opt was not found in your PATH: skipping the optimized build\n");
        put (f, bat, "goto :succeeded\n");
        put (f, bat, "\n:failed\n");
        put (f, bat, "echo.\n");
        put (f, bat, "echo BUILD FAILED\n");
        put (f, bat, "exit /b 1\n");
        put (f, bat, "\n:succeeded\n");
        put (f, bat, "echo.\n");
        put (f, bat, "echo BUILD SUCCESSFUL\n");
        put (f, bat, "exit /b 0\n");
    }
    else
    {
        put (f, bat, "\nif command -v v32opt >/dev/null 2>&1; then\n");
        put (f, bat, "    echo\n");
        put (f, bat, "    echo Build the optimized cart \\(v32opt\\)\n");
        put (f, bat, "    echo --------------------------\n");
        put (f, bat, "    if v32opt -O3 -o %s %s \\\n", word (0, plan->asm_opt), word (0, plan->asm_file));
        put (f, bat, "       && assemble%s %s -o %s \\\n", dbg, word (0, plan->asm_opt), word (0, plan->vbin_opt));
        put (f, bat, "       && packrom %s -o %s; then\n", word (0, plan->xml_opt), word (0, plan->rom_opt));
        put (f, bat, "        :\n");
        put (f, bat, "    else\n");
        put (f, bat, "        echo\n");
        put (f, bat, "        echo \"WARNING: the optimized build failed; the regular cart was still built\"\n");
        put (f, bat, "    fi\n");
        put (f, bat, "else\n");
        put (f, bat, "    echo\n");
        put (f, bat, "    echo \"v32opt was not found in your PATH: skipping the optimized build\"\n");
        put (f, bat, "fi\n");
        put (f, bat, "\necho\n");
        put (f, bat, "echo BUILD SUCCESSFUL\n");
    }
}

// Writes `name` in the plan's script folder, unless a script v32lua did not
// write is already there.
static void write_one (const Plan *plan, const char *name, int bat, int verbose)
{
    char *path = join_path (plan->script_dir, name);
    FILE *old  = fopen (path, "rb");

    if (old != NULL)
    {
        char head[600] = { 0 };
        size_t got = fread (head, 1, sizeof (head) - 1, old);
        fclose (old);
        head[got] = '\0';
        if (strstr (head, GENERATED_MARK) == NULL)
        {
            compiler_warning (ERR_INTERNAL, -1,
                "%s already exists and was not written by v32lua; leaving it alone "
                "(--no-build-scripts stops this warning)", path);
            free (path);
            return;
        }
    }

    FILE *f = fopen (path, "wb");
    if (f == NULL)
    {
        compiler_warning (ERR_INTERNAL, -1, "could not write build script '%s'", path);
        free (path);
        return;
    }
    write_script (f, bat, plan);
    fclose (f);
#ifndef _WIN32
    if (!bat) chmod (path, 0755);
#endif
    if (verbose)
    {
        char *shown = path_relative_to (".", path);
        fprintf (stdout, "saving build script %s\n", shown);
        free (shown);
    }
    free (path);
}

void emit_build_scripts (const char *output_filename, const char *source_filename,
                         int preserve_paths, int debug_map,
                         const BuildOpt *opts, int nopts, int verbose)
{
    Plan   plan;
    char  *src_dir   = path_dirname (source_filename);
    char  *out_dir   = path_dirname (output_filename);

    memset (&plan, 0, sizeof (plan));

    // Project folder: beside the source, or one up when the source is in
    // "src" and the output goes to a sibling folder (src/ and obj/).
    {
        char *proj = path_project_dir (source_filename, output_filename);
        plan.script_dir = path_absolute (proj);
        free (proj);
    }

    plan.opts       = opts;
    plan.nopts      = nopts;
    plan.debug_map  = debug_map;

    // Paths of the build, relative to the script folder.
    char *vbin_full  = replace_extension (output_filename, ".vbin");
    char *asm_opt    = replace_extension (output_filename, "Opt.asm");
    char *vbin_opt   = replace_extension (output_filename, "Opt.vbin");
    char *xml_full   = cart_xml_filename (output_filename, source_filename, preserve_paths);
    char *xml_opt    = replace_extension (xml_full, "Opt.xml");
    char *xml_dir    = path_dirname (xml_full);
    char *base       = replace_extension (path_basename (output_filename), "");

    plan.name       = base;
    plan.input      = rel (&plan, source_filename);
    plan.asm_file   = rel (&plan, output_filename);
    plan.asm_opt    = rel (&plan, asm_opt);
    plan.vbin       = rel (&plan, vbin_full);
    plan.vbin_opt   = rel (&plan, vbin_opt);
    plan.xml        = rel (&plan, xml_full);
    plan.xml_opt    = rel (&plan, xml_opt);

    char *rom_name     = malloc (strlen (base) + 16);
    char *rom_opt_name = malloc (strlen (base) + 20);
    if (rom_name == NULL || rom_opt_name == NULL) { fprintf (stderr, "Compiler Error: out of memory\n"); exit (2); }
    sprintf (rom_name,     "bin/%s.v32",    base);
    sprintf (rom_opt_name, "bin/%sOpt.v32", base);
    plan.rom        = rom_name;
    plan.rom_opt    = rom_opt_name;

    add_dir_of (&plan, plan.asm_file);          // obj/
    add_dir (&plan, "bin");
    plan_assets (&plan, textures_head, 1, xml_dir, src_dir, preserve_paths);
    plan_assets (&plan, sounds_head,   0, xml_dir, src_dir, preserve_paths);
    add_dir_of (&plan, plan.xml);

    write_one (&plan, "Make.sh",  0, verbose);
    write_one (&plan, "Make.bat", 1, verbose);

    for (int i = 0; i < plan.nassets; i++) { free (plan.assets[i].src); free (plan.assets[i].dest); }
    for (int i = 0; i < plan.ndirs; i++) free (plan.dirs[i]);
    free (plan.assets); free (plan.dirs);
    free (plan.name); free (plan.input); free (plan.asm_file); free (plan.asm_opt);
    free (plan.vbin); free (plan.vbin_opt); free (plan.xml); free (plan.xml_opt);
    free (plan.rom); free (plan.rom_opt); free (plan.script_dir);
    free (vbin_full); free (asm_opt); free (vbin_opt); free (xml_full); free (xml_opt);
    free (xml_dir); free (src_dir); free (out_dir);
}
